CN = "宋体"      # 中文
EN = "Times New Roman"  # 西文


def new_doc():
    d = docx.Document(TPL)
    body = d.element.body
    for child in list(body.iterchildren()):
        if child.tag == qn("w:sectPr"):
            continue
        body.remove(child)
    return d


def _set(run, size=12, bold=False, color=None):
    """双字体：中文 宋体 + 西文 Times New Roman"""
    run.font.name = EN                     # 西文默认
    rPr = run._element.rPr
    rFonts = rPr.rFonts if rPr.rFonts is not None else rPr.makeelement(qn("w:rFonts"), {})
    rFonts.set(qn("w:eastAsia"), CN)       # 中文字体
    rFonts.set(qn("w:ascii"), EN)          # ASCII
    rFonts.set(qn("w:hAnsi"), EN)          # 高位 ANSI
    rPr.insert(0, rFonts)
    run.font.size = Pt(size)
    run.font.bold = bold
    if color:
        run.font.color.rgb = color


def _para(d, text, style="Normal Indent", size=12, bold=False, align=None, space=4, indent=Pt(24)):
    p = d.add_paragraph(style=style)
    r = p.add_run(text)
    _set(r, size=size, bold=bold)
    if align is not None:
        p.alignment = align
    p.paragraph_format.space_after = Pt(space)
    if style == "Normal Indent" and indent is not None:
        p.paragraph_format.first_line_indent = indent
    return p


def h1(d, t):
    return d.add_paragraph(t, style="Heading 1")


def para(d, t, size=12, bold=False):
    return _para(d, t, "Normal Indent", size=size, bold=bold)


def bullet(d, t, size=12):
    return _para(d, t, "Normal Indent", size=size, indent=Pt(0))


def table(d, rows, header=True):
    ncol = max(len(r) for r in rows)
    t = d.add_table(rows=0, cols=ncol)
    t.style = "Table Grid"
    t.alignment = WD_ALIGN_PARAGRAPH.CENTER
    for ri, row in enumerate(rows):
        cells = t.add_row().cells
        for ci in range(ncol):
            cells[ci].text = ""
            r = cells[ci].paragraphs[0].add_run(str(row[ci]) if ci < len(row) else "")
            _set(r, size=10.5, bold=(header and ri == 0))
    return t


def caption(d, text):
    p = d.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    r = p.add_run(text)
    _set(r, size=10.5, bold=True, color=RGBColor(0x40, 0x40, 0x40))


def figure(d, img_name, cap, width=None):
    path = os.path.join(IMG, img_name) if img_name else None
    w = Inches(width) if width else Inches(5.3)
    if path and os.path.exists(path):
        p = d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(path, width=w)
    else:
        p = d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run("〔此处为示意图，留待补入〕")
        _set(r, size=11, color=RGBColor(0x90, 0x90, 0x90))
    caption(d, cap)


def shot(d, filename, cap, width=None):
    path = os.path.join(SHOT, filename) if filename else None
    w = Inches(width) if width else Inches(5.5)
    if path and os.path.exists(path):
        p = d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.add_run().add_picture(path, width=w)
    else:
        p = d.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run("〔待补截图：" + cap + "〕")
        _set(r, size=11, color=RGBColor(0x90, 0x90, 0x90))
    caption(d, cap)


def section(d, num, title):
    p = d.add_paragraph(style="Normal Indent")
    r = p.add_run(num + " " + title)
